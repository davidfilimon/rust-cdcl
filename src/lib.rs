//! SAT solver CDCL educational. No third-party dependencies.
use std::collections::HashSet;
use std::time::{Duration, Instant};

#[derive(Clone, Debug)]
pub struct Cnf {
    pub variables: usize,
    pub clauses: Vec<Vec<i32>>,
}

pub fn parse_dimacs(text: &str) -> Result<Cnf, String> {
    let mut vars: Option<usize> = None;
    let mut total: Option<usize> = None;
    let mut clauses = Vec::new();
    let mut clause = Vec::new();
    for (ln, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('c') || line.starts_with('%') {
            continue;
        }
        if line.starts_with('p') {
            let parts: Vec<_> = line.split_whitespace().collect();
            if vars.is_some() || parts.len() != 4 || parts[0] != "p" || parts[1] != "cnf" {
                return Err(format!(
                    "line {}: invalid or duplicate 'p cnf' header",
                    ln + 1
                ));
            }
            vars = Some(parts[2].parse().map_err(|_| "invalid variable count")?);
            total = Some(parts[3].parse().map_err(|_| "invalid clause count")?);
            continue;
        }
        let n = vars.ok_or_else(|| format!("line {}: missing DIMACS header", ln + 1))?;
        for item in line.split_whitespace() {
            if item == "c" {
                break;
            }
            let lit: i32 = item
                .parse()
                .map_err(|_| format!("line {}: invalid literal {item}", ln + 1))?;
            if lit == 0 {
                clauses.push(std::mem::take(&mut clause));
            } else {
                let v = lit.unsigned_abs() as usize;
                if v > n || v == 0 {
                    return Err(format!("line {}: literal outside 1..={n}", ln + 1));
                }
                clause.push(lit);
            }
        }
    }
    let n = vars.ok_or("missing DIMACS header")?;
    if !clause.is_empty() {
        return Err("last clause missing terminator 0".into());
    }
    if Some(clauses.len()) != total {
        return Err(format!(
            "expected {} clauses, received {}",
            total.unwrap_or(0),
            clauses.len()
        ));
    }
    if n > i32::MAX as usize {
        return Err("variable count too large".into());
    }
    Ok(Cnf {
        variables: n,
        clauses,
    })
}

pub fn write_dimacs(cnf: &Cnf) -> String {
    let mut s = format!(
        "c generated by cdcl-rust\np cnf {} {}\n",
        cnf.variables,
        cnf.clauses.len()
    );
    for clause in &cnf.clauses {
        for lit in clause {
            s.push_str(&format!("{} ", lit));
        }
        s.push_str("0\n");
    }
    s
}

pub fn verify_model(cnf: &Cnf, model: &[bool]) -> bool {
    if model.len() <= cnf.variables {
        return false;
    }
    cnf.clauses.iter().all(|clause| {
        clause.iter().any(|&lit| {
            let v = lit.unsigned_abs() as usize;
            if v == 0 || v > cnf.variables {
                return false;
            }
            if lit > 0 {
                model[v]
            } else {
                !model[v]
            }
        })
    })
}

#[derive(Clone, Debug)]
pub struct Options {
    pub timeout: Option<Duration>,
    pub max_conflicts: Option<u64>,
    pub restart_base: u64,
    pub enable_restarts: bool,
    pub enable_reduction: bool,
    pub vsids: bool,
    pub trace: bool,
}
impl Default for Options {
    fn default() -> Self {
        Self {
            timeout: None,
            max_conflicts: None,
            restart_base: 64,
            enable_restarts: true,
            enable_reduction: true,
            vsids: true,
            trace: false,
        }
    }
}

#[derive(Clone, Debug, Default)]
pub struct Stats {
    pub decisions: u64,
    pub propagations: u64,
    pub conflicts: u64,
    pub learned_clauses: u64,
    pub deleted_clauses: u64,
    pub restarts: u64,
    pub backjumps: u64,
    pub elapsed: Duration,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Status {
    Sat(Vec<bool>),
    Unsat,
    Unknown,
}

#[derive(Debug, Clone)]
struct Clause {
    lits: Vec<i32>,
    learnt: bool,
    deleted: bool,
    activity: f64,
    lbd: usize,
}

fn lit_index(lit: i32) -> usize {
    let v = lit.unsigned_abs() as usize - 1;
    2 * v + usize::from(lit < 0)
}
fn var(lit: i32) -> usize {
    lit.unsigned_abs() as usize
}

/// Luby sequence: 1,1,2,1,1,2,4,... (1-based index).
fn luby(i: u64) -> u64 {
    let mut size = 1u64;
    let mut seq = 0;
    while size < i + 1 {
        seq += 1;
        size = 2 * size + 1;
    }
    let mut x = i;
    while size - 1 != x {
        size = (size - 1) >> 1;
        seq -= 1;
        x %= size;
    }
    1u64 << seq
}

pub struct Solver {
    n: usize,
    clauses: Vec<Clause>,
    watches: Vec<Vec<usize>>,
    values: Vec<i8>, // 0 unassigned, 1 true, -1 false
    levels: Vec<usize>,
    reasons: Vec<Option<usize>>,
    saved_polarity: Vec<i8>,
    trail: Vec<i32>,
    trail_limits: Vec<usize>,
    qhead: usize,
    var_activity: Vec<f64>,
    var_inc: f64,
    clause_inc: f64,
    // Indexed max-heap: maximum VSIDS score first, O(log n) per update/decision.
    heap: Vec<usize>,     // 1-indexed, position 0 unused
    heap_pos: Vec<usize>, // 0 means not in heap
    seen: Vec<u32>,       // reusable analysis marks (no per-conflict allocation)
    seen_epoch: u32,
    lbd_marks: Vec<u32>, // reusable decision-level marks
    lbd_epoch: u32,
    impossible: bool,
    pub stats: Stats,
    opts: Options,
}

impl Solver {
    pub fn new(cnf: &Cnf, opts: Options) -> Self {
        let n = cnf.variables;
        let mut s = Self {
            n,
            clauses: Vec::new(),
            watches: vec![Vec::new(); 2 * n],
            values: vec![0; n + 1],
            levels: vec![0; n + 1],
            reasons: vec![None; n + 1],
            saved_polarity: vec![1; n + 1],
            trail: Vec::new(),
            trail_limits: Vec::new(),
            qhead: 0,
            var_activity: vec![0.0; n + 1],
            var_inc: 1.0,
            clause_inc: 1.0,
            heap: vec![0],
            heap_pos: vec![0; n + 1],
            seen: vec![0; n + 1],
            seen_epoch: 0,
            lbd_marks: vec![0; n + 1],
            lbd_epoch: 0,
            impossible: false,
            stats: Stats::default(),
            opts,
        };
        if s.opts.trace {
            println!(
                "[START] Pornesc CDCL cu {} variabile si {} clauze.",
                n,
                cnf.clauses.len()
            );
            println!(
                "[START] Formulele sunt in CNF. Caut o atribuire care satisface toate clauzele."
            );
        }
        for (original_index, raw) in cnf.clauses.iter().enumerate() {
            if s.opts.trace {
                println!(
                    "[INPUT] Clauza originala C{} = {:?}",
                    original_index + 1,
                    raw
                );
            }
            let mut lits = Vec::new();
            let mut seen = HashSet::new();
            let mut tautology = false;
            for &lit in raw {
                if lit == 0 || var(lit) > n {
                    s.impossible = true;
                    break;
                }
                if seen.contains(&-lit) {
                    tautology = true;
                    break;
                }
                if seen.insert(lit) {
                    lits.push(lit);
                }
            }
            if tautology {
                if s.opts.trace {
                    println!(
                        "[INPUT] Tautologie: C{} este mereu adevarata; o ignor.",
                        original_index + 1
                    );
                }
                continue;
            }
            if lits.is_empty() {
                if s.opts.trace {
                    println!(
                        "[CONTRADICTIE] Clauza vida C{}: UNSAT imediat.",
                        original_index + 1
                    );
                }
                s.impossible = true;
                continue;
            }
            let ci = s.add_clause(lits, false, 0);
            if s.clauses[ci].lits.len() == 1 {
                let lit = s.clauses[ci].lits[0];
                if !s.enqueue(lit, Some(ci)) {
                    if s.opts.trace {
                        println!(
                            "[CONTRADICTIE] Clauza unitara {:?} contrazice atribuirea curenta.",
                            s.clauses[ci].lits
                        );
                    }
                    s.impossible = true;
                }
            }
        }
        // Initialize VSIDS with a light occurrence/Jeroslow-Wang score instead of
        // assigning every variable activity zero and always branching on x1.
        if s.opts.vsids {
            let mut polarity = vec![0.0f64; n + 1];
            for c in &s.clauses {
                let weight = 2f64.powi(-(c.lits.len().min(30) as i32));
                for &lit in &c.lits {
                    let v = var(lit);
                    s.var_activity[v] += weight;
                    polarity[v] += if lit > 0 { weight } else { -weight };
                }
            }
            for v in 1..=n {
                // For unassigned vars, start with the statistically preferred phase.
                if s.values[v] == 0 {
                    s.saved_polarity[v] = if polarity[v] < 0.0 { -1 } else { 1 };
                }
                s.heap_push(v);
            }
        }
        s
    }
    fn add_clause(&mut self, lits: Vec<i32>, learnt: bool, lbd: usize) -> usize {
        let ci = self.clauses.len();
        if lits.len() >= 2 {
            self.watches[lit_index(lits[0])].push(ci);
            self.watches[lit_index(lits[1])].push(ci);
        }
        self.clauses.push(Clause {
            lits,
            learnt,
            deleted: false,
            activity: 0.0,
            lbd,
        });
        ci
    }
    fn level(&self) -> usize {
        self.trail_limits.len()
    }
    fn val(&self, lit: i32) -> i8 {
        let x = self.values[var(lit)];
        if lit < 0 {
            -x
        } else {
            x
        }
    }
    fn enqueue(&mut self, lit: i32, reason: Option<usize>) -> bool {
        let v = var(lit);
        if self.values[v] != 0 {
            return self.val(lit) == 1;
        }
        self.values[v] = if lit > 0 { 1 } else { -1 };
        self.saved_polarity[v] = self.values[v];
        self.levels[v] = self.level();
        self.reasons[v] = reason;
        self.trail.push(lit);
        if self.opts.trace {
            match reason {
                Some(ci) => println!(
                    "[PROPAGARE] Nivel {}: x{} = {} deoarece clauza {:?} obliga literalul {}",
                    self.level(),
                    v,
                    self.values[v] == 1,
                    self.clauses[ci].lits,
                    lit
                ),
                None => println!(
                    "[DECIZIE] Nivel {}: aleg x{} = {} (literal {}).",
                    self.level(),
                    v,
                    self.values[v] == 1,
                    lit
                ),
            }
            println!("[TRAIL] {:?}", self.trail);
        }
        true
    }
    /// Two-watched-literals Boolean Constraint Propagation.
    /// Uses swap_remove in the existing watch lists: no allocation per propagated literal.
    fn propagate(&mut self) -> Option<usize> {
        while self.qhead < self.trail.len() {
            let p = self.trail[self.qhead];
            self.qhead += 1;
            self.stats.propagations += 1;
            if self.opts.trace {
                println!(
                    "[BCP] Examinez efectele lui {} (literalul {} devine fals).",
                    p, -p
                );
            }
            let false_lit = -p;
            let wi = lit_index(false_lit);
            let mut i = 0;
            while i < self.watches[wi].len() {
                let ci = self.watches[wi][i];
                if self.clauses[ci].deleted {
                    self.watches[wi].swap_remove(i);
                    continue;
                }
                // The false watched literal goes into position 1.
                if self.clauses[ci].lits[0] == false_lit {
                    self.clauses[ci].lits.swap(0, 1);
                }
                if self.clauses[ci].lits[1] != false_lit {
                    self.watches[wi].swap_remove(i);
                    continue;
                }
                let other = self.clauses[ci].lits[0];
                if self.val(other) == 1 {
                    i += 1;
                    continue;
                }
                // Find a watched-literal replacement not currently false.
                let mut replacement_index = None;
                for k in 2..self.clauses[ci].lits.len() {
                    if self.val(self.clauses[ci].lits[k]) != -1 {
                        replacement_index = Some(k);
                        break;
                    }
                }
                if let Some(k) = replacement_index {
                    let replacement = self.clauses[ci].lits[k];
                    self.clauses[ci].lits[1] = replacement;
                    self.clauses[ci].lits[k] = false_lit;
                    self.watches[wi].swap_remove(i);
                    self.watches[lit_index(replacement)].push(ci);
                } else {
                    if self.val(other) == -1 || !self.enqueue(other, Some(ci)) {
                        if self.opts.trace {
                            println!(
                                "[CONFLICT] Clauza {:?} este falsa la nivelul {}.",
                                self.clauses[ci].lits,
                                self.level()
                            );
                            println!("[CONFLICT] Atribuirile curente: {:?}", self.trail);
                        }
                        // No temporary list exists, so all remaining watches remain intact.
                        return Some(ci);
                    }
                    i += 1;
                }
            }
        }
        None
    }
    // The indexed heap holds unassigned or stale assigned variables; removing
    // assigned variables lazily avoids an O(log n) operation per unit propagation.
    fn heap_better(&self, a: usize, b: usize) -> bool {
        self.var_activity[a] > self.var_activity[b]
            || (self.var_activity[a] == self.var_activity[b] && a < b)
    }
    fn heap_swap(&mut self, i: usize, j: usize) {
        self.heap.swap(i, j);
        self.heap_pos[self.heap[i]] = i;
        self.heap_pos[self.heap[j]] = j;
    }
    fn heap_up(&mut self, mut i: usize) {
        while i > 1 {
            let parent = i / 2;
            if !self.heap_better(self.heap[i], self.heap[parent]) {
                break;
            }
            self.heap_swap(i, parent);
            i = parent;
        }
    }
    fn heap_down(&mut self, mut i: usize) {
        loop {
            let mut child = 2 * i;
            if child >= self.heap.len() {
                break;
            }
            if child + 1 < self.heap.len()
                && self.heap_better(self.heap[child + 1], self.heap[child])
            {
                child += 1;
            }
            if !self.heap_better(self.heap[child], self.heap[i]) {
                break;
            }
            self.heap_swap(i, child);
            i = child;
        }
    }
    fn heap_push(&mut self, v: usize) {
        if self.heap_pos[v] != 0 || self.values[v] != 0 {
            return;
        }
        let pos = self.heap.len();
        self.heap.push(v);
        self.heap_pos[v] = pos;
        self.heap_up(pos);
    }
    fn heap_pop(&mut self) -> Option<usize> {
        if self.heap.len() == 1 {
            return None;
        }
        let result = self.heap[1];
        let last = self.heap.pop().expect("nonempty heap");
        self.heap_pos[result] = 0;
        if self.heap.len() > 1 {
            self.heap[1] = last;
            self.heap_pos[last] = 1;
            self.heap_down(1);
        }
        Some(result)
    }
    fn bump_var(&mut self, v: usize) {
        self.var_activity[v] += self.var_inc;
        let at = self.heap_pos[v];
        if at != 0 {
            self.heap_up(at);
        }
        if self.var_activity[v] > 1e100 {
            for a in &mut self.var_activity {
                *a *= 1e-100;
            }
            self.var_inc *= 1e-100;
        }
    }
    fn bump_clause(&mut self, ci: usize) {
        self.clauses[ci].activity += self.clause_inc;
        if self.clauses[ci].activity > 1e100 {
            for c in &mut self.clauses {
                c.activity *= 1e-100;
            }
            self.clause_inc *= 1e-100;
        }
    }
    /// First-UIP conflict analysis. Reuses marking arrays and iterates directly
    /// over clause literals without cloning each reason clause.
    fn analyze(&mut self, mut conflict: usize) -> (Vec<i32>, usize, usize) {
        let mut learnt = vec![0];
        self.seen_epoch = self.seen_epoch.wrapping_add(1);
        if self.seen_epoch == 0 {
            self.seen.fill(0);
            self.seen_epoch = 1;
        }
        let epoch = self.seen_epoch;
        let mut pending = 0usize;
        let mut idx = self.trail.len();
        let mut pivot = 0i32;
        if self.opts.trace {
            println!(
                "[ANALIZA] First-UIP: pornesc de la clauza in conflict {:?}.",
                self.clauses[conflict].lits
            );
        }
        loop {
            self.bump_clause(conflict);
            if self.opts.trace {
                println!(
                    "[REZOLUTIE] Folosesc clauza {:?}, pivotul anterior {}.",
                    self.clauses[conflict].lits, pivot
                );
            }
            for j in 0..self.clauses[conflict].lits.len() {
                let q = self.clauses[conflict].lits[j];
                let v = var(q);
                if q == pivot || self.seen[v] == epoch || self.levels[v] == 0 {
                    continue;
                }
                self.seen[v] = epoch;
                self.bump_var(v);
                if self.levels[v] == self.level() {
                    pending += 1;
                } else {
                    learnt.push(q);
                }
            }
            let p = loop {
                idx -= 1;
                let p = self.trail[idx];
                if self.seen[var(p)] == epoch {
                    break p;
                }
            };
            pivot = p;
            self.seen[var(p)] = 0;
            pending -= 1;
            if pending == 0 {
                learnt[0] = -p;
                break;
            }
            conflict = self.reasons[var(p)].expect("1-UIP: implied pivot must have reason");
        }
        let mut back = 0;
        if learnt.len() > 1 {
            let mut at = 1;
            for i in 2..learnt.len() {
                if self.levels[var(learnt[i])] > self.levels[var(learnt[at])] {
                    at = i;
                }
            }
            learnt.swap(1, at);
            back = self.levels[var(learnt[1])];
        }
        self.lbd_epoch = self.lbd_epoch.wrapping_add(1);
        if self.lbd_epoch == 0 {
            self.lbd_marks.fill(0);
            self.lbd_epoch = 1;
        }
        let mut lbd = 0;
        for &lit in &learnt {
            let level = self.levels[var(lit)];
            if self.lbd_marks[level] != self.lbd_epoch {
                self.lbd_marks[level] = self.lbd_epoch;
                lbd += 1;
            }
        }
        self.var_inc /= 0.95;
        self.clause_inc /= 0.999;
        if self.opts.trace {
            println!(
                "[INVATARE] Clauza noua {:?}; LBD = {}; backjump la nivelul {}.",
                learnt, lbd, back
            );
            println!(
                "[INVATARE] Literalul {} devine obligatoriu dupa backjump.",
                learnt[0]
            );
        }
        (learnt, back, lbd)
    }
    fn backtrack(&mut self, target: usize) {
        if self.level() <= target {
            return;
        }
        let keep = self.trail_limits[target];
        if self.opts.trace {
            println!(
                "[BACKJUMP] Revin de la nivelul {} la {}. Anulez {:?}.",
                self.level(),
                target,
                &self.trail[keep..]
            );
        }
        for i in keep..self.trail.len() {
            let v = var(self.trail[i]);
            self.values[v] = 0;
            self.levels[v] = 0;
            self.reasons[v] = None;
            if self.opts.vsids {
                self.heap_push(v);
            }
        }
        self.trail.truncate(keep);
        self.trail_limits.truncate(target);
        self.qhead = self.trail.len();
    }
    fn choose(&mut self) -> Option<i32> {
        if self.opts.vsids {
            while let Some(v) = self.heap_pop() {
                if self.values[v] == 0 {
                    return Some((v as i32) * i32::from(self.saved_polarity[v]));
                }
            }
            return None;
        }
        for v in 1..=self.n {
            if self.values[v] == 0 {
                return Some((v as i32) * i32::from(self.saved_polarity[v]));
            }
        }
        None
    }
    /// Remove only unlocked long learnt clauses; reason clauses cannot be deleted.
    fn reduce_db(&mut self) {
        let locked: HashSet<usize> = self.reasons.iter().filter_map(|&reason| reason).collect();
        let mut candidates: Vec<usize> = self
            .clauses
            .iter()
            .enumerate()
            .filter(|(i, c)| {
                c.learnt && !c.deleted && c.lits.len() > 2 && c.lbd > 2 && !locked.contains(i)
            })
            .map(|(i, _)| i)
            .collect();
        candidates.sort_by(|&a, &b| {
            self.clauses[b].lbd.cmp(&self.clauses[a].lbd).then_with(|| {
                self.clauses[a]
                    .activity
                    .total_cmp(&self.clauses[b].activity)
            })
        });
        for ci in candidates.into_iter().take(self.clauses.len() / 8) {
            self.clauses[ci].deleted = true;
            self.stats.deleted_clauses += 1;
        }
        // Watch lists are cleaned lazily in propagate().
    }
    pub fn solve(&mut self) -> Status {
        let start = Instant::now();
        let result = self.solve_inner(start);
        self.stats.elapsed = start.elapsed();
        result
    }
    fn solve_inner(&mut self, start: Instant) -> Status {
        if self.impossible {
            if self.opts.trace {
                println!("[FINAL] UNSAT: exista clauza vida sau unitati initiale contradictorii.");
            }
            return Status::Unsat;
        }
        if let Some(ci) = self.propagate() {
            if self.opts.trace {
                println!(
                    "[FINAL] UNSAT: la nivelul 0, clauza {:?} este falsa.",
                    self.clauses[ci].lits
                );
            }
            return Status::Unsat;
        }
        let mut restart_id = 1u64;
        let mut next_restart = self
            .opts
            .restart_base
            .saturating_mul(luby(restart_id - 1))
            .max(1);
        loop {
            if self.opts.timeout.is_some_and(|t| start.elapsed() >= t) {
                if self.opts.trace {
                    println!("[FINAL] UNKNOWN: s-a depasit Tmax.");
                }
                return Status::Unknown;
            }
            if let Some(conflict) = self.propagate() {
                self.stats.conflicts += 1;
                if self.opts.trace {
                    println!(
                        "[CONFLICT] Conflictul #{} la nivelul {} in clauza {:?}.",
                        self.stats.conflicts,
                        self.level(),
                        self.clauses[conflict].lits
                    );
                }
                if self.level() == 0 {
                    if self.opts.trace {
                        println!("[FINAL] UNSAT: conflict la nivelul 0. Nu mai exista decizii de anulat.");
                        println!(
                            "[FINAL] Conflictul cu clauza {:?} demonstreaza nesatisfiabilitatea.",
                            self.clauses[conflict].lits
                        );
                    }
                    return Status::Unsat;
                }
                let (learnt, back, lbd) = self.analyze(conflict);
                if self.opts.trace {
                    println!(
                        "[CDCL] Pregatesc clauza invatata {:?} (LBD {}).",
                        learnt, lbd
                    );
                }
                if back + 1 < self.level() {
                    self.stats.backjumps += 1;
                }
                self.backtrack(back);
                let assert_lit = learnt[0];
                let ci = self.add_clause(learnt, true, lbd);
                self.stats.learned_clauses += 1;
                assert!(
                    self.enqueue(assert_lit, Some(ci)),
                    "learnt clause must assert"
                );
                if self
                    .opts
                    .max_conflicts
                    .is_some_and(|lim| self.stats.conflicts >= lim)
                {
                    if self.opts.trace {
                        println!("[FINAL] UNKNOWN: limita de conflicte a fost atinsa.");
                    }
                    return Status::Unknown;
                }
                if self.opts.enable_reduction && self.stats.conflicts % 250 == 0 {
                    self.reduce_db();
                }
                if self.opts.enable_restarts && self.stats.conflicts >= next_restart {
                    if self.opts.trace {
                        println!(
                            "[RESTART] Repornire #{}: pastrez clauzele invatate.",
                            self.stats.restarts + 1
                        );
                    }
                    self.backtrack(0);
                    self.stats.restarts += 1;
                    restart_id += 1;
                    next_restart = next_restart.saturating_add(
                        self.opts
                            .restart_base
                            .saturating_mul(luby(restart_id - 1))
                            .max(1),
                    );
                }
            } else {
                match self.choose() {
                    None => {
                        let mut model = vec![false; self.n + 1];
                        for (v, val) in self.values.iter().enumerate().skip(1) {
                            model[v] = *val == 1;
                        }
                        if self.opts.trace {
                            println!(
                                "[FINAL] SAT: toate variabilele sunt atribuite fara conflict."
                            );
                            for v in 1..=self.n {
                                println!("[MODEL] x{} = {}", v, model[v]);
                            }
                        }
                        return Status::Sat(model);
                    }
                    Some(lit) => {
                        self.trail_limits.push(self.trail.len());
                        self.stats.decisions += 1;
                        assert!(self.enqueue(lit, None));
                    }
                }
            }
        }
    }
}

/// Deterministic xorshift RNG, to keep project dependency-free.
#[derive(Clone)]
pub struct Rng(pub u64);
impl Rng {
    pub fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        if x == 0 {
            x = 0x9e3779b97f4a7c15;
        }
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        x
    }
    pub fn range(&mut self, n: usize) -> usize {
        (self.next_u64() % n as u64) as usize
    }
}

pub fn random_ksat(n: usize, m: usize, k: usize, seed: u64) -> Result<Cnf, String> {
    if n == 0 || k == 0 || k > n || n > i32::MAX as usize {
        return Err("require 1 <= k <= n <= i32::MAX".into());
    }
    let mut rng = Rng(seed);
    let mut clauses = Vec::with_capacity(m);
    for _ in 0..m {
        let mut clause = Vec::with_capacity(k);
        let mut used = HashSet::new();
        while clause.len() < k {
            let v = rng.range(n) + 1;
            if used.insert(v) {
                clause.push((v as i32) * if rng.range(2) == 0 { 1 } else { -1 });
            }
        }
        clauses.push(clause);
    }
    Ok(Cnf {
        variables: n,
        clauses,
    })
}

/// n+1 pigeons in n holes: unsatisfiable for n>=1.
pub fn pigeonhole(n: usize) -> Result<Cnf, String> {
    if n == 0 || n > 5000 || (n + 1).saturating_mul(n) > i32::MAX as usize {
        return Err("pigeonhole requires 1 <= n <= 5000".into());
    }
    let id = |p: usize, h: usize| (p * n + h + 1) as i32;
    let mut clauses = Vec::new();
    for p in 0..=n {
        clauses.push((0..n).map(|h| id(p, h)).collect());
    }
    for h in 0..n {
        for a in 0..=n {
            for b in a + 1..=n {
                clauses.push(vec![-id(a, h), -id(b, h)]);
            }
        }
    }
    Ok(Cnf {
        variables: (n + 1) * n,
        clauses,
    })
}

/// N queens: one queen per row, and no column or diagonal conflicts.
pub fn nqueens(n: usize) -> Result<Cnf, String> {
    if n == 0 || n > 64 {
        return Err("queens requires 1 <= n <= 64".into());
    }
    let id = |r: usize, c: usize| (r * n + c + 1) as i32;
    let mut clauses = Vec::new();
    for r in 0..n {
        clauses.push((0..n).map(|c| id(r, c)).collect());
        for c in 0..n {
            for d in c + 1..n {
                clauses.push(vec![-id(r, c), -id(r, d)]);
            }
        }
    }
    for c in 0..n {
        for r in 0..n {
            for s in r + 1..n {
                clauses.push(vec![-id(r, c), -id(s, c)]);
            }
        }
    }
    for r in 0..n {
        for c in 0..n {
            for s in r + 1..n {
                for d in 0..n {
                    if r.abs_diff(s) == c.abs_diff(d) {
                        clauses.push(vec![-id(r, c), -id(s, d)]);
                    }
                }
            }
        }
    }
    Ok(Cnf {
        variables: n * n,
        clauses,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    fn run(cnf: &Cnf) -> Status {
        let mut solver = Solver::new(cnf, Options::default());
        let status = solver.solve();
        if let Status::Sat(ref model) = status {
            assert!(verify_model(cnf, model));
        }
        status
    }
    fn brute(cnf: &Cnf) -> bool {
        assert!(cnf.variables <= 10);
        (0..(1 << cnf.variables)).any(|mask| {
            let mut m = vec![false; cnf.variables + 1];
            for (v, val) in m.iter_mut().enumerate().skip(1) {
                *val = (mask >> (v - 1)) & 1 == 1;
            }
            verify_model(cnf, &m)
        })
    }
    #[test]
    fn sat_small() {
        let c = parse_dimacs("c test\np cnf 3 3\n1 2 0\n-1 3 0\n-2 -3 0\n").unwrap();
        assert!(matches!(run(&c), Status::Sat(_)));
    }
    #[test]
    fn unsat_units() {
        let c = parse_dimacs("p cnf 1 2\n1 0\n-1 0").unwrap();
        assert_eq!(run(&c), Status::Unsat);
    }
    #[test]
    fn empty_clause_and_formula() {
        assert_eq!(run(&parse_dimacs("p cnf 2 1\n0").unwrap()), Status::Unsat);
        assert!(matches!(
            run(&parse_dimacs("p cnf 0 0\n").unwrap()),
            Status::Sat(_)
        ));
    }
    #[test]
    fn duplicates_and_tautologies() {
        let c = parse_dimacs("p cnf 2 3\n1 1 0\n1 -1 0\n-1 2 0").unwrap();
        assert!(matches!(run(&c), Status::Sat(_)));
    }
    #[test]
    fn malformed_dimacs() {
        for s in ["1 0", "p cnf 1 1\n2 0", "p cnf 1 1\n1", "p cnf 1 2\n1 0"] {
            assert!(parse_dimacs(s).is_err(), "accepted {s}");
        }
    }
    #[test]
    fn pigeonhole_unsat() {
        for n in 1..=4 {
            assert_eq!(run(&pigeonhole(n).unwrap()), Status::Unsat);
        }
    }
    #[test]
    fn queens_known() {
        assert!(matches!(run(&nqueens(1).unwrap()), Status::Sat(_)));
        assert_eq!(run(&nqueens(2).unwrap()), Status::Unsat);
        assert_eq!(run(&nqueens(3).unwrap()), Status::Unsat);
        assert!(matches!(run(&nqueens(4).unwrap()), Status::Sat(_)));
    }
    #[test]
    fn timeout_unknown() {
        let mut options = Options::default();
        options.timeout = Some(Duration::ZERO);
        let c = pigeonhole(4).unwrap();
        assert_eq!(Solver::new(&c, options).solve(), Status::Unknown);
    }
    #[test]
    fn deterministic_random_matches_bruteforce() {
        for n in 1..=7 {
            for seed in 1..=60 {
                let k = n.min(3);
                let c = random_ksat(n, 4 * n + 2, k, 17 * seed + n as u64).unwrap();
                assert_eq!(
                    matches!(run(&c), Status::Sat(_)),
                    brute(&c),
                    "n={n} seed={seed}"
                );
            }
        }
    }
    #[test]
    fn random_mixed_clause_sizes_matches_bruteforce() {
        let mut rng = Rng(98321);
        for _ in 0..200 {
            let n = rng.range(7) + 1;
            let m = rng.range(25);
            let mut clauses = vec![];
            for _ in 0..m {
                let k = rng.range(5);
                let mut clause = vec![];
                for _ in 0..k {
                    let v = (rng.range(n) + 1) as i32;
                    clause.push(if rng.range(2) == 0 { v } else { -v });
                }
                clauses.push(clause);
            }
            let c = Cnf {
                variables: n,
                clauses,
            };
            assert_eq!(matches!(run(&c), Status::Sat(_)), brute(&c), "{c:?}");
        }
    }
    #[test]
    fn restart_sequence() {
        assert_eq!(
            (0..8).map(luby).collect::<Vec<_>>(),
            vec![1, 1, 2, 1, 1, 2, 4, 1]
        );
    }
    #[test]
    fn conflict_limit() {
        let mut options = Options::default();
        options.max_conflicts = Some(1);
        let c = pigeonhole(3).unwrap();
        assert_eq!(Solver::new(&c, options).solve(), Status::Unknown);
    }
}
